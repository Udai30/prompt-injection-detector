"""Rebuild ``reports/results.csv`` and ``results.md`` from all finished runs (TRD §S4).

One row per (variant, subset). Rows from a run whose hard-negative set is still the agent draft
are marked ``draft`` and kept out of the markdown headline table (CLAUDE.md §5).
"""

from __future__ import annotations

import csv
import json
from collections.abc import Iterable
from pathlib import Path
from typing import Any, Final

COLUMNS: Final = [
    "run_id",
    "detector",
    "variant",
    "subset",
    "hn_status",
    "threshold",
    "n",
    "n_attacks",
    "n_benign",
    "recall",
    "recall_ci",
    "fpr",
    "fpr_ci",
    "precision",
    "f1",
    "latency_p50_ms",
    "latency_p95_ms",
    "list_cost_per_1k_usd",
    "n_errors",
]
SUBSET_ORDER: Final = {"validation": 0, "test": 1, "hard_negative": 2}


def load_summaries(runs_dir: Path) -> list[dict[str, Any]]:
    summaries: list[dict[str, Any]] = []
    for path in sorted(runs_dir.glob("*/summary.json")):
        summaries.append(json.loads(path.read_text(encoding="utf-8")))
    return summaries


def _fmt(value: float | None, digits: int = 3) -> str:
    return "" if value is None else f"{value:.{digits}f}"


def _ci(block: dict[str, Any]) -> str:
    low, high = block["ci_low"], block["ci_high"]
    return "" if low is None or high is None else f"[{low:.3f}, {high:.3f}]"


def _row(summary: dict[str, Any], metric_block: dict[str, Any], language: str) -> dict[str, str]:
    m = metric_block
    latency = summary["latency_ms"]
    return {
        "run_id": summary["run_id"],
        "detector": summary["detector"],
        "variant": summary["variant"] + ("" if language == "all" else f" [{language}]"),
        "subset": summary["dataset_split"],
        "hn_status": summary["hn_status"],
        "threshold": _fmt(summary["threshold"]),
        "n": str(m["n"]),
        "n_attacks": str(m["n_attacks"]),
        "n_benign": str(m["n_benign"]),
        "recall": _fmt(m["recall"]["value"]),
        "recall_ci": _ci(m["recall"]),
        "fpr": _fmt(m["fpr"]["value"]),
        "fpr_ci": _ci(m["fpr"]),
        "precision": _fmt(m["precision"]["value"]),
        "f1": _fmt(m["f1"]["value"]),
        "latency_p50_ms": _fmt(latency["p50"], 1),
        "latency_p95_ms": _fmt(latency["p95"], 1),
        "list_cost_per_1k_usd": _fmt(
            None
            if summary["list_cost_usd_per_1k"] is None
            else float(summary["list_cost_usd_per_1k"]),
            4,
        ),
        "n_errors": str(summary["n_errors"]),
    }


def rows_from(summaries: Iterable[dict[str, Any]]) -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for summary in summaries:
        rows.append(_row(summary, summary["metrics"], "all"))
        for language, block in summary["by_language"].items():
            rows.append(_row(summary, block, language))
    rows.sort(
        key=lambda r: (
            r["detector"],
            r["variant"].split(" [")[0],
            SUBSET_ORDER.get(r["subset"], 9),
            "[" in r["variant"],
            r["variant"],
        )
    )
    return rows


def write_csv(rows: list[dict[str, str]], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=COLUMNS, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def _cell(value: str, ci: str) -> str:
    return "-" if not value else f"{value} {ci}".strip()


def markdown(rows: list[dict[str, str]]) -> str:
    """Headline table: overall rows only, per subset; draft hard-negative rows are flagged."""
    lines = [
        "# Results",
        "",
        "Generated by `injection_bench report build`; every number comes from a run in `runs/`.",
        "Recall on deepset test/validation; FPR on the hard negatives (all benign) and on the "
        "benign deepset prompts. 95 % bootstrap CIs in brackets. English/German rows are in "
        "`results.csv`.",
        "",
        "| Detector | Variant | Subset | n | Recall | FPR | Precision | F1 | p50 ms | p95 ms "
        "| $/1k |",
        "|---|---|---|---:|---|---|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        if "[" in r["variant"]:
            continue
        subset = r["subset"] + (" (DRAFT set)" if r["hn_status"] == "draft" else "")
        lines.append(
            f"| {r['detector']} | {r['variant']} | {subset} | {r['n']} | "
            f"{_cell(r['recall'], r['recall_ci'])} | {_cell(r['fpr'], r['fpr_ci'])} | "
            f"{r['precision'] or '-'} | {r['f1'] or '-'} | {r['latency_p50_ms'] or '-'} | "
            f"{r['latency_p95_ms'] or '-'} | {r['list_cost_per_1k_usd'] or '-'} |"
        )
    lines += [
        "",
        "Rows marked DRAFT use the agent-drafted hard-negative candidates, not the human-accepted "
        "set: provisional, not for the README.",
    ]
    return "\n".join(lines) + "\n"


def build(runs_dir: Path, reports_dir: Path) -> list[dict[str, str]]:
    rows = rows_from(load_summaries(runs_dir))
    write_csv(rows, reports_dir / "results.csv")
    (reports_dir / "results.md").write_text(markdown(rows), encoding="utf-8", newline="\n")
    return rows
